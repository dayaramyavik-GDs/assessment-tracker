const fs = require('fs');
const path = require('path');

const env = process.argv[2] || 'dev';
const urls = {
  dev: process.env.API_DEV_URL || 'http://localhost:3000/api',
  prod: process.env.API_PROD_URL || 'https://assessment-tracker-api.onrender.com/api', // change after deploying
};
if (!urls[env]) { console.error(`Unknown environment "${env}". Use dev or prod.`); process.exit(1); }
if (env === 'prod' && !urls.prod.startsWith('https://')) { console.error('Production API URL must start with https://'); process.exit(1); }

const content = `// Generated by scripts/set-config.js (${env}). Do not edit by hand.
window.AT_CONFIG = Object.freeze(${JSON.stringify({ API_BASE_URL: urls[env], ENV: env }, null, 2)});
`;
fs.writeFileSync(path.join(__dirname, '..', 'www', 'js', 'config.js'), content);
console.log(`www/js/config.js -> ${urls[env]}`);